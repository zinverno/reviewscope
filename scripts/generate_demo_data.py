def main() -> int:
    DATA_DIR.mkdir(exist_ok=True)
    rng = random.Random(SEED)
    builder = _ReviewBuilder(rng)

    reviews: list[NormalizedReview] = []
    metas: list[dict] = []

    organic = _build_organic_history(rng, builder)
    reviews.extend(organic)

    burst, burst_meta = _build_positive_burst(rng, builder)
    reviews.extend(burst)
    metas.append(burst_meta)

    bombing, bombing_meta = _build_negative_bombing(rng, builder)
    reviews.extend(bombing)
    metas.append(bombing_meta)

    dup_group, dup_meta = _build_duplicate_group(rng, builder)
    reviews.extend(dup_group)
    metas.append(dup_meta)

    if len(reviews) < MIN_REVIEWS:
        raise SystemExit(f"only {len(reviews)} reviews generated, need >= {MIN_REVIEWS}")

    # Deterministic ordering by place then date for a stable file.
    records = [
        {
            "review_id": r.review_id,
            "place_id": r.place_id,
            "place_name": r.place_name,
            "place_category": r.place_category,
            "reviewer_id": r.reviewer_id,
            "reviewer_name": r.reviewer_name,
            "rating": r.rating,
            "text": r.text,
            "published_at": r.published_at,
            "city": r.city,
            "region": r.region,
            "country": r.country,
            "latitude": r.latitude,
            "longitude": r.longitude,
            "source": r.source,
            "source_url": r.source_url,
        }
        for r in sorted(reviews, key=lambda x: (x.published_at or "", x.review_id))
    ]

    import csv

    with open(CSV_PATH, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(records[0].keys()))
        writer.writeheader()
        writer.writerows(records)
    with open(JSON_PATH, "w", encoding="utf-8") as fh:
        json.dump({"reviews": records}, fh, ensure_ascii=False, indent=1)
    with open(META_PATH, "w", encoding="utf-8") as fh:
        json.dump({"anomalies": metas}, fh, ensure_ascii=False, indent=2)

    print(f"Generated {len(records)} reviews")
    print(f"  places: {len(PLACES_BY_ID)}")
    print(f"  → {CSV_PATH}")
    print(f"  → {JSON_PATH}")
    print(f"  → {META_PATH}")

    # Self-check: re-import through the real adapters and show validation report.
    csv_result = CSVAdapter().load(CSV_PATH)
    print("\nCSV self-check:")
    print(csv_result.report.summary_display())
    json_result = JSONAdapter().load(JSON_PATH)
    print("\nJSON self-check:")
    print(json_result.report.summary_display())

    assert csv_result.report.skipped == 0, "unexpected skipped rows in demo CSV"
    assert csv_result.report.valid >= MIN_REVIEWS, "CSV round-trip lost reviews"
    assert json_result.report.valid >= MIN_REVIEWS, "JSON round-trip lost reviews"
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
