def _personalize_text(
    rng: random.Random,
    used: set[str],
    core: str,
    fragments: list[str],
) -> str:
    """Append personal details so genuine organic reviews stay unique.

    Several fragments are combined to make the text substantially longer than
    the shared template core; combined with the global ``used`` set this keeps
    organic reviews distinct, while injected anomaly batches deliberately reuse
    byte-identical texts.  The first fragment is placed *before* the core so
    that reviews sharing the same core no longer share a long identical prefix.
    """
    for _ in range(20):
        k = rng.randint(2, 3)
        picks = rng.sample(fragments, k)
        lead = picks[0]
        tail = " ".join(picks[1:]) if k > 1 else ""
        text = f"{lead}. {core}" if not tail else f"{lead}. {core} {tail}"
        if text not in used:
            used.add(text)
            return text
    text = core
    suffix = 1
    while text in used:
        text = f"{core} [#{suffix}]"
        suffix += 1
    used.add(text)
    return text


