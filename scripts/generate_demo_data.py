def _specific_details(rng: random.Random, category: str) -> str:
    """Append one concrete, per-review detail drawn from large pools.

    The detail (proper name + drink/dish/item) makes the organic text genuinely
    unique, so shared n-grams stay below the templated detector's phrase-reuse
    bar (SPEC.md §7 item 7, §16). Random slots mean adjacent pairs rarely
    repeat even within a large place cohort, while the surrounding fragment
    sentences provide personal context.
    """
    pool = SPECIFIC_DETAILS.get(category) or SPECIFIC_DETAILS["coffee"]
    selected = rng.sample(pool, 1)
    return " ".join(
        tpl.format(**{k: rng.choice(v) for k, v in slots.items()})
        for tpl, slots in selected
    )


def _organic_composition(rng: random.Random, category: str) -> str:
    """Compose a unique organic review body from randomized clauses.

    Positive clause pools are preferred 62/38 like a real review base rate.
    Each clause carries per-review slot values, so identical 2-3 word runs
    across reviews are rare and organic texts stay genuinely unique; only the
    injected anomaly batches intentionally reuse wording (SPEC §16).
    """
    positive = rng.random() < 0.62
    pool = POSITIVE_CLAUSES.get(category) or POSITIVE_CLAUSES["coffee"]
    if not positive:
        pool = NEGATIVE_CLAUSES.get(category) or NEGATIVE_CLAUSES["coffee"]
    selected = rng.sample(pool, rng.randint(2, 3))
    clauses = [tpl.format(**{k: rng.choice(v) for k, v in slots.items()}) for tpl, slots in selected]
    body = " ".join(clauses)
    return f"{body}. {_specific_details(rng, category)}."


