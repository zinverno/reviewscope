def _template_family_texts(rng: random.Random, family: dict, count: int) -> list[str]:
    """Render ``count`` distinct instances of a template family.

    The walk visits product() combinations at a stride coprime to the combo
    count, so every combination in the slice is distinct and each slot value
    appears about ``count / pool`` times (at most one apart). That keeps each
    (literal, value) phrase shared by at least ``phrase_reuse_min_peers + 1``
    members of the place, so the whole batch sits at full phrase-reuse coverage
    regardless of sampling luck.
    """
    from itertools import product

    keys = list(family["slots"])
    pools = [list(v) for v in family["slots"].values()]
    for pool in pools:
        rng.shuffle(pool)
    combos = list(product(*pools))
    size = len(combos)
    stride = 5 % size or 1
    while size % stride == 0:
        stride += 2
    start = rng.randrange(size)
    return [
        family["skeleton"].format(**dict(zip(keys, combo, strict=False)))
        for combo in (combos[(start + i * stride) % size] for i in range(count))
    ]

